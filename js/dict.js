  var index = Object.create(null);
  var tagIndex = Object.create(null);
  var all = [];

  function normalize(row, src) {
    var tags = String(row[6] || '').split(/[,，]/).map(function (s) { return s.trim(); }).filter(Boolean);
    return {
      term: String(row[0] || '').trim(),
      key: String(row[0] || '').trim().toLowerCase(),
      pos: row[1] || '',
      cn: row[2] || '',
      ipa: row[3] || '',
      ex: row[4] || '',
      exCn: row[5] || '',
      tags: tags,
      srcIds: [src.id]
    };
  }

  SOURCES.forEach(function (src) {
    src.map = Object.create(null);
    src.words.forEach(function (row) {
      var e = normalize(row, src);
      if (!e.term) return;
      src.map[e.key] = e;
      if (!index[e.key]) {
        index[e.key] = e;
        all.push(e);
      } else {
        // 同一单词出现在多份词表中：合并来源，并补齐缺失字段
        var t = index[e.key];
        if (t.srcIds.indexOf(src.id) < 0) t.srcIds.push(src.id);
        if (!t.pos && e.pos) t.pos = e.pos;
        if (!t.cn && e.cn) t.cn = e.cn;
        if (!t.ipa && e.ipa) t.ipa = e.ipa;
        if (!t.ex && e.ex) { t.ex = e.ex; t.exCn = e.exCn; }
        e = t;
      }
      e.tags.forEach(function (tag) {
        var k = tag;
        if (!tagIndex[k]) tagIndex[k] = [];
        if (tagIndex[k].indexOf(e) < 0) tagIndex[k].push(e);
      });
    });
  });

  // 查词顺序：内置词库 → 你自己录过的所有生词（录过一次，以后就能自动带出释义）
  function get(term) {
    var k = String(term || '').trim().toLowerCase();
    if (!k) return null;
    var hit = index[k];
    if (hit) return hit;
    if (VL.store && VL.store.findAnyWord) {
      var mine = VL.store.findAnyWord(k);
      if (mine) {
        return {
          term: mine.term, key: mine.key, pos: mine.pos || '', cn: mine.meaning || '',
          ipa: (mine.phonetic || '').replace(/^\/|\/$/g, ''), ex: mine.example || '', exCn: mine.exampleCn || '',
          tags: mine.tags || [], srcIds: ['user'], from: 'user'
        };
      }
    }
    return null;
  }
  function has(term) { return !!get(term); }

  // 查词：内置词库优先，未收录时返回一个空词条骨架，方便用户自行补全
  function lookup(term) {
    var found = get(term);
    if (found) return Object.assign({}, found, { found: true });
    return { term: String(term || '').trim(), key: String(term || '').trim().toLowerCase(), pos: '', cn: '', ipa: '', ex: '', exCn: '', tags: [], srcIds: [], found: false };
  }

  function byTag(tag) { return (tagIndex[tag] || []).slice(); }

  // 候选词：在某份词表内（或全部词库）挑出满足词性 / 标签约束的词
  function candidates(sourceId, opts) {
    var o = opts || {};
    var pool;
    if (sourceId && sourceId !== 'all') {
      var src = getSource(sourceId);
      pool = src ? Object.keys(src.map).map(function (k) { return src.map[k]; }) : all.slice();
    } else {
      pool = all.slice();
    }
    return pool.filter(function (e) {
      if (o.pos && o.pos.length && o.pos.indexOf(e.pos) < 0) return false;
      if (o.tags && o.tags.length) {
        if (!e.tags.some(function (t) { return o.tags.indexOf(t) >= 0; })) return false;
      }
      if (o.needExample && !e.ex) return false;
      if (o.exclude && o.exclude.indexOf(e.key) >= 0) return false;
      return true;
    });
  }

  function getSource(id) {
    for (var i = 0; i < SOURCES.length; i++) if (SOURCES[i].id === id) return SOURCES[i];
    return null;
  }

  function sources() {
    return SOURCES.map(function (s) {
      return { id: s.id, name: s.name, short: s.short, kind: s.kind, stage: s.stage, grade: s.grade, count: s.words.length };
    });
  }

  VL.dict = {
    TAG_LABELS: TAG_LABELS,
    get: get, has: has, lookup: lookup, byTag: byTag, candidates: candidates,
    sources: sources, getSource: getSource,
    all: function () { return all.slice(); },
    size: function () { return all.length; }
  };
